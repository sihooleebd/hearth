#!/usr/bin/env python3
"""hearth -- a tiny schema-driven settings store with a change-diff signal.

Generic + app-agnostic. Point it at a directory holding a `schema.json` (a flat registry of typed
setting records) and it manages everything else: user overrides, a materialised NESTED `settings.json`
that every consumer reads, and a `settings.signal.json` carrying the exact keys that changed on each
write -- a "git diff" for config -- so a consumer reloads only the parts it owns.

Files in $HEARTH_DIR (default $XDG_STATE_HOME/hearth):
  schema.json          INPUT  (generated by the app)   { "settings": { "a.b.c": {type,default,...} },
                                                          "groups": { "a": {label,order,icon} } }
  overrides.json       managed  flat { "a.b.c": <value> }  -- ONLY user-changed keys (survives rebuilds)
  settings.json        OUTPUT   nested effective values + "_version"  -- what consumers read
  settings.signal.json OUTPUT   { "version", "changed": [keys], "ts" }

CLI:
  hearth get <key>              print the effective value (JSON)
  hearth set <key> <value>      validate against the schema, override, re-materialise, signal
  hearth reset <key>            drop an override (back to default)
  hearth dump                   print the whole effective store (nested JSON)
  hearth sync                   re-materialise from schema defaults + overrides; signal diffs (on rebuild)
  hearth watch [prefix ...]     block; on each change print the changed keys (space-separated) that fall
                                under one of the prefixes -- for shell consumers:
                                    hearth watch panel | while read -r keys; do reload $keys; done
"""
import os
import re
import sys
import json
import time

DIR = os.environ.get("HEARTH_DIR") or os.path.join(
    os.environ.get("XDG_STATE_HOME", os.path.expanduser("~/.local/state")), "hearth")
SCHEMA = os.path.join(DIR, "schema.json")
OVERRIDE = os.path.join(DIR, "overrides.json")
STORE = os.path.join(DIR, "settings.json")
SIGNAL = os.path.join(DIR, "settings.signal.json")

HEX = re.compile(r"^#([0-9a-fA-F]{6}|[0-9a-fA-F]{8})$")


def die(msg):
    sys.stderr.write(f"hearth: {msg}\n")
    sys.exit(1)


def _load(path, fallback):
    try:
        with open(path) as f:
            return json.load(f)
    except Exception:
        return fallback


def _atomic(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = f"{path}.tmp.{os.getpid()}"
    with open(tmp, "w") as f:
        json.dump(obj, f, indent=2, sort_keys=True)
        f.write("\n")
    os.replace(tmp, path)                       # atomic: no consumer ever sees a half-written file


def _schema():
    s = _load(SCHEMA, {})
    if isinstance(s, dict) and "settings" in s:
        return s["settings"]
    return s if isinstance(s, dict) else {}


# ------- flatten / nest: the dotted key is the bridge between flat registry and nested store -------
def _nest(flat):
    root = {}
    for k, v in flat.items():
        d = root
        parts = k.split(".")
        for p in parts[:-1]:
            d = d.setdefault(p, {})
        d[parts[-1]] = v
    return root


def _flat(nested, prefix=""):
    out = {}
    for k, v in nested.items():
        if prefix == "" and k == "_version":
            continue
        key = prefix + k
        if isinstance(v, dict):
            out.update(_flat(v, key + "."))
        else:
            out[key] = v
    return out


def _effective():
    """default (from the schema) overlaid with the user's override, for every declared key."""
    sch, ov = _schema(), _load(OVERRIDE, {})
    return {k: (ov[k] if k in ov else ent.get("default")) for k, ent in sch.items()}


# ----------------------------- validation / coercion -----------------------------
def _coerce(ent, raw):
    """Parse a CLI string (or a JSON value) into the schema type; raise ValueError if it doesn't fit."""
    t = ent.get("type", "string")
    c = ent.get("constraints") or {}
    if t == "bool":
        return raw if isinstance(raw, bool) else str(raw).strip().lower() in ("1", "true", "yes", "on")
    if t in ("int", "float"):
        v = int(raw) if t == "int" else float(raw)
        if "min" in c and v < c["min"]:
            raise ValueError(f"{v} below min {c['min']}")
        if "max" in c and v > c["max"]:
            raise ValueError(f"{v} above max {c['max']}")
        return v
    if t == "enum":
        opts = [o["value"] if isinstance(o, dict) else o for o in (c.get("options") or [])]
        if raw not in opts:
            raise ValueError(f"{raw!r} not one of {opts}")
        return raw
    if t == "color":
        if not HEX.match(str(raw)):
            raise ValueError(f"{raw!r} is not #rrggbb or #rrggbbaa")
        return str(raw)
    if t == "list":
        if isinstance(raw, list):
            return raw
        raw = raw.strip()
        return json.loads(raw) if raw.startswith("[") else [x for x in raw.split(",") if x]
    s = str(raw)                                # string, font, path, keybind, unknown
    if "maxLength" in c and len(s) > c["maxLength"]:
        raise ValueError(f"longer than {c['maxLength']}")
    if "pattern" in c and not re.search(c["pattern"], s):
        raise ValueError(f"does not match /{c['pattern']}/")
    return s


# ----------------------------- the core: materialise + signal -----------------------------
def sync():
    """Recompute settings.json from schema defaults + overrides; emit the diff signal. Returns the
    list of changed keys. The first-ever materialise (no store yet) bootstraps SILENTLY -- consumers
    read the fresh store on start, so there's nothing to notify about a change from nothing."""
    bootstrap = not os.path.exists(STORE)
    new = _effective()
    prev = _flat(_load(STORE, {}))
    changed = sorted(k for k in set(new) | set(prev) if new.get(k) != prev.get(k))
    ver = _load(STORE, {}).get("_version", 0) + (1 if changed else 0)
    store = _nest(new)
    store["_version"] = ver
    _atomic(STORE, store)
    if changed and not bootstrap:
        _atomic(SIGNAL, {"version": ver, "changed": changed, "ts": int(time.time())})
    return changed


# ----------------------------- CLI -----------------------------
def cmd_set(key, raw):
    sch = _schema()
    if key not in sch:
        die(f"unknown setting: {key}")
    try:
        val = _coerce(sch[key], raw)
    except Exception as e:
        die(f"invalid value for {key}: {e}")
    ov = _load(OVERRIDE, {})
    ov[key] = val
    _atomic(OVERRIDE, ov)
    sync()
    print(json.dumps(val))


def cmd_get(key):
    eff = _effective()
    if key not in eff:
        die(f"unknown setting: {key}")
    print(json.dumps(eff[key]))


def cmd_reset(key):
    ov = _load(OVERRIDE, {})
    if key in ov:
        del ov[key]
        _atomic(OVERRIDE, ov)
        sync()
    print("ok")


def _mtime(path):
    try:
        return os.stat(path).st_mtime
    except OSError:
        return 0


def cmd_watch(prefixes):
    def owned(k):
        return not prefixes or any(k == p or k.startswith(p + ".") for p in prefixes)

    last_ver = _load(SIGNAL, {}).get("version", 0)
    last_mtime = _mtime(SIGNAL)
    while True:
        time.sleep(0.2)
        m = _mtime(SIGNAL)
        if m == last_mtime:
            continue
        last_mtime = m
        sig = _load(SIGNAL, {})
        ver = sig.get("version", 0)
        changed = [k for k in sig.get("changed", []) if owned(k)]
        if ver - last_ver > 1:                  # we missed signals (restart?) -> reload everything we own
            changed = sorted(k for k in _effective() if owned(k))
        last_ver = ver
        if changed:
            print(" ".join(changed), flush=True)


def main():
    a = sys.argv[1:]
    if not a:
        die("usage: hearth get|set|reset|dump|sync|watch ...")
    cmd = a[0]
    if cmd == "get" and len(a) == 2:
        cmd_get(a[1])
    elif cmd == "set" and len(a) >= 3:
        cmd_set(a[1], " ".join(a[2:]))
    elif cmd == "reset" and len(a) == 2:
        cmd_reset(a[1])
    elif cmd == "dump":
        print(json.dumps(_nest(_effective()), indent=2, sort_keys=True))
    elif cmd == "sync":
        print(" ".join(sync()))
    elif cmd == "watch":
        cmd_watch(a[1:])
    else:
        die(f"bad args: {a}")
    return 0


if __name__ == "__main__":
    main()
